BEGIN
    ALTER TABLE public.usuarios ALTER COLUMN usuario_id SET GENERATED BY DEFAULT;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

DO $$
BEGIN
    ALTER TABLE public.salas ALTER COLUMN sala_id SET GENERATED BY DEFAULT;
EXCEPTION WHEN OTHERS THEN NULL;
END $$;

